// Builds src/data.generated.ts from the matprat.no ingredient measurement API.
// Run with: node scripts/build-data.ts
//
// The API returns, per ingredient, the weight in grams of one unit
// (deciliter, tablespoon, ounce, ...). That is exactly the density table we
// need to turn "3 ss hvetemel" into grams.

import { writeFileSync } from "node:fs";

const API = "https://www.matprat.no/api/IngredientMeasurement/GetAllIngredients";
const OUT = new URL("../src/data.generated.ts", import.meta.url);

const KEEP_UNITS = [
  "liter",
  "deciliter",
  "centiliter",
  "milliliter",
  "cup", // Norwegian "kopp"
  "uscup", // American "kopp"
  "teaspoon", // ts
  "tablespoon", // ss
  "piece", // stk.
  "ounce", // unse
  "pound", // pund
] as const;

type UnitInfo = { name?: string; weight?: number | null } | null;
type Row = { id: number; name: string; units: Record<string, UnitInfo> };

const round = (n: number): number => Math.round(n * 100) / 100;

async function main(): Promise<void> {
  const res = await fetch(API, {
    headers: { Referer: "https://www.matprat.no/", Accept: "application/json" },
  });
  if (!res.ok) throw new Error(`matprat API responded ${res.status}`);

  const rows = (await res.json()) as Row[];
  const ingredients: { n: string; u: Record<string, number> }[] = [];
  let keptUnits = 0;

  for (const row of rows) {
    const name = (row.name ?? "").trim().toLowerCase();
    if (!name) continue;
    const u: Record<string, number> = {};
    for (const key of KEEP_UNITS) {
      const info = row.units?.[key];
      if (!info || typeof info.weight !== "number" || info.weight <= 0) continue;
      u[key] = round(info.weight);
    }
    if (Object.keys(u).length === 0) continue;
    keptUnits += Object.keys(u).length;
    ingredients.push({ n: name, u });
  }

  const banner = [
    "// AUTO-GENERATED by scripts/build-data.ts -- do not edit by hand.",
    "// Source: https://www.matprat.no/api/IngredientMeasurement/GetAllIngredients",
    `// Generated: ${new Date().toISOString()}`,
    `// ${ingredients.length} ingredients, ${keptUnits} unit weights.`,
    "",
    "export type UnitKey =",
    KEEP_UNITS.map((k) => `  | "${k}"`).join("\n") + ";",
    "",
    "export interface IngredientEntry {",
    "  n: string;",
    "  u: Partial<Record<UnitKey, number>>;",
    "}",
    "",
  ].join("\n");

  const body =
    "export const MATPRAT_INGREDIENTS: IngredientEntry[] = " +
    JSON.stringify(ingredients) +
    ";\n";

  writeFileSync(OUT, banner + body);
  console.log(
    `wrote ${OUT.pathname} -- ${ingredients.length} ingredients (${(
      (banner.length + body.length) /
      1024
    ).toFixed(0)} KB)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
